/**
 * LOAD TEST — seed N throwaway users, measure the admin queries, remove them.
 *
 *   npm run qa:load -- --seed 1000
 *   npm run qa:load -- --measure
 *   npm run qa:load -- --remove
 *
 * WHY THIS EXISTS
 * A portal that works with six users tells you nothing about one with a
 * thousand. The queries that break are the ones that scan the whole table, and
 * they only reveal themselves once the table is big.
 *
 * SAFETY
 * Every seeded row uses the RFC 2606 reserved domain `snz-loadtest.invalid`,
 * which can never be a real address, and `--remove` deletes exactly that set.
 * Nothing else is touched. Run `--remove` when finished: these are real rows in
 * a real database until you do.
 */
import "./lib/env.mjs";
import postgres from "postgres";

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 && process.argv[i + 1] && !process.argv[i + 1].startsWith("--")
    ? process.argv[i + 1]
    : fallback;
};

const DOMAIN = "snz-loadtest.invalid";
const mode = process.argv.includes("--remove")
  ? "remove"
  : process.argv.includes("--measure")
    ? "measure"
    : process.argv.includes("--seed")
      ? "seed"
      : null;

if (!mode) {
  console.error("\n  Usage: --seed <n> | --measure | --remove\n");
  process.exit(1);
}

const sql = postgres(process.env.DATABASE_URL, {
  max: 1,
  ssl: "require",
  prepare: false,
  connect_timeout: 15,
});

const time = async (label, fn) => {
  const t = Date.now();
  const r = await fn();
  const ms = Date.now() - t;
  const flag = ms > 1000 ? "SLOW" : "ok  ";
  console.log(`  ${flag}  ${label.padEnd(46)} ${String(ms).padStart(5)}ms  ${r ?? ""}`);
  return ms;
};

try {
  if (mode === "seed") {
    const n = Number(arg("seed", "1000"));
    console.log(`\n  Seeding ${n} users on @${DOMAIN} …`);

    /*
      One INSERT for the lot, generated by Postgres. A thousand round trips
      from here would take minutes and would be measuring my network rather
      than the database.

      The password hash is a fixed, deliberately unusable literal — these
      accounts must never be signed into, and generating a real scrypt hash a
      thousand times would take longer than the rest of the script.
    */
    const t = Date.now();
    await sql`
      INSERT INTO users (email, name, role, status, password_hash, email_verified, created_at)
      SELECT
        'load' || i || '@${sql.unsafe(DOMAIN)}',
        'Load Test ' || i,
        (ARRAY['student','professional','business']::user_role[])[1 + (i % 3)],
        (ARRAY['active','active','active','pending','suspended']::user_status[])[1 + (i % 5)],
        'scrypt$65536$8$1$loadtest$notarealhash',
        (i % 2 = 0),
        now() - (i || ' minutes')::interval
      FROM generate_series(1, ${n}) AS i
      ON CONFLICT DO NOTHING
    `;
    await sql`
      INSERT INTO profiles (user_id, phone, nationality, country)
      SELECT id, '+370600' || substr(md5(id::text), 1, 5), 'Pakistani', 'Pakistan'
      FROM users WHERE email LIKE ${"%@" + DOMAIN}
      ON CONFLICT DO NOTHING
    `;
    const [{ n: total }] = await sql`
      SELECT count(*)::int AS n FROM users WHERE email LIKE ${"%@" + DOMAIN}`;
    console.log(`  seeded in ${Date.now() - t}ms — ${total} load-test users present\n`);
  }

  if (mode === "measure" || mode === "seed") {
    const [{ n: totalUsers }] = await sql`SELECT count(*)::int AS n FROM users`;
    console.log(`\n  Measuring against ${totalUsers} total users\n`);

    await time("admin dashboard (getAdminOverview)", async () => {
      const [r] = await sql`
        SELECT json_build_object(
          'totalUsers',(SELECT count(*)::int FROM users),
          'students',(SELECT count(*)::int FROM users WHERE role='student'),
          'professionals',(SELECT count(*)::int FROM users WHERE role='professional'),
          'businesses',(SELECT count(*)::int FROM users WHERE role='business'),
          'openCases',(SELECT count(*)::int FROM cases WHERE status NOT IN ('completed','closed')),
          'pendingDocuments',(SELECT count(*)::int FROM documents WHERE status IN ('uploaded','pending_review')),
          'unreadMessages',(SELECT count(*)::int FROM messages WHERE read_at IS NULL),
          'totalQueries',(SELECT count(*)::int FROM intake_forms WHERE status <> 'draft')
        ) AS m,
        COALESCE((SELECT json_agg(x) FROM (
          SELECT c.id,c.title,u.name AS cn FROM cases c JOIN users u ON u.id=c.client_id
          ORDER BY c.updated_at DESC LIMIT 12) x),'[]'::json) AS cases,
        COALESCE((SELECT json_agg(x) FROM (
          SELECT id,email,name,role FROM users ORDER BY created_at DESC LIMIT 8) x),'[]'::json) AS recent
      `;
      return `users=${r.m.totalUsers}`;
    });

    await time("users page 1 of 25 (unfiltered)", async () => {
      const r = await sql`
        SELECT u.id,u.email,u.name,u.role,u.status,u.created_at, count(*) OVER () AS total_count
        FROM users u ORDER BY u.created_at DESC LIMIT 25 OFFSET 0`;
      return `total=${r[0]?.total_count ?? 0}`;
    });

    await time("users page 20 (deep offset)", async () => {
      const r = await sql`
        SELECT u.id,u.email,u.name,u.role, count(*) OVER () AS total_count
        FROM users u ORDER BY u.created_at DESC LIMIT 25 OFFSET 475`;
      return `rows=${r.length}`;
    });

    await time("search by name (leading wildcard)", async () => {
      const r = await sql`
        SELECT u.id,u.name, count(*) OVER () AS total_count FROM users u
        WHERE u.name ILIKE ${"%test 4%"} OR u.email ILIKE ${"%test 4%"}
        ORDER BY u.created_at DESC LIMIT 25`;
      return `matches=${r[0]?.total_count ?? 0}`;
    });

    await time("filter role=student + status=active", async () => {
      const r = await sql`
        SELECT u.id, count(*) OVER () AS total_count FROM users u
        WHERE u.role='student' AND u.status='active'
        ORDER BY u.created_at DESC LIMIT 25`;
      return `matches=${r[0]?.total_count ?? 0}`;
    });

    await time("sidebar badges (one statement)", async () => {
      const [id] = await sql`SELECT id FROM users WHERE role='super_admin' LIMIT 1`;
      await sql`
        SELECT
          (SELECT count(*)::int FROM messages m WHERE m.read_at IS NULL AND m.author_id <> ${id.id}) AS messages,
          (SELECT count(*)::int FROM notifications n WHERE n.user_id=${id.id} AND n.read_at IS NULL) AS notifications,
          (SELECT count(*)::int FROM documents d WHERE d.status IN ('uploaded','pending_review')) AS documents,
          (SELECT count(*)::int FROM tasks t WHERE t.assignee_id=${id.id} AND t.status<>'done') AS tasks`;
      return "";
    });

    await time("query analytics", async () => {
      await sql`
        SELECT
          COALESCE((SELECT json_agg(x) FROM (
            SELECT status::text AS key, count(*)::int AS count FROM intake_forms GROUP BY status) x),'[]'::json) AS by_status,
          COALESCE((SELECT json_agg(x) FROM (
            SELECT to_char(date_trunc('week',submitted_at),'YYYY-MM-DD') AS week, count(*)::int AS count
            FROM intake_forms WHERE submitted_at IS NOT NULL AND submitted_at >= now() - interval '12 weeks'
            GROUP BY date_trunc('week',submitted_at)) x),'[]'::json) AS over_time`;
      return "";
    });

    console.log("\n  SLOW = over 1000ms. Anything flagged needs an index or a rewrite.\n");
  }

  if (mode === "remove") {
    const gone = await sql`
      DELETE FROM users WHERE email LIKE ${"%@" + DOMAIN} RETURNING id`;
    console.log(`\n  Removed ${gone.length} load-test user(s).\n`);
  }
} catch (error) {
  console.error("\n  Failed:", error instanceof Error ? error.message : error);
  process.exitCode = 1;
} finally {
  await sql.end({ timeout: 5 });
}
